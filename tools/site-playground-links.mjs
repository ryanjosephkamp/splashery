// The Playground's links follow pages on disk, never a hand-maintained toy list.
// The site build runs this after writing and pruning its pages. It can also run
// alone: node tools/site-playground-links.mjs [--check].
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";
import { TOYS } from "../src/toys.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src/site-toy-pages.js");

export function siteToyPageIds({ siteDir = path.join(root, "site"), toys = TOYS } = {}) {
  return toys
    .filter((toy) => fs.existsSync(path.join(siteDir, "toys", toy.id, "index.html")))
    .map((toy) => toy.id)
    .sort();
}

export async function buildPlaygroundLinks({ check = false } = {}) {
  const config = await prettier.resolveConfig(output);
  const source = await prettier.format(
    `// Generated by tools/site-playground-links.mjs; only pages that exist at build time.\nexport const SITE_TOY_IDS = ${JSON.stringify(siteToyPageIds())};\n`,
    { ...config, parser: "babel" },
  );
  if (fs.existsSync(output) && fs.readFileSync(output, "utf8") === source) return true;
  if (check) {
    console.log("out of date: src/site-toy-pages.js (run node tools/site-playground-links.mjs)");
    return false;
  }
  fs.writeFileSync(output, source);
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (!(await buildPlaygroundLinks({ check: process.argv.includes("--check") })))
    process.exitCode = 1;
}
