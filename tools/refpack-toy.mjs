#!/usr/bin/env node
// Publish only the five explicitly licensed test builds, never arbitrary packs.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import * as prettier from "prettier";
import { SAMPLES } from "./refpack-samples.mjs";
import { loadPack } from "./refpack.mjs";

const builds = SAMPLES.map((sample) => {
  const dir = path.join("tools/refpack-samples", sample.id),
    pack = loadPack(dir);
  if (pack.license.images !== "CC0-1.0")
    throw new Error("Only the CC0 benchmark fixtures may enter this toy.");
  const score = JSON.parse(fs.readFileSync(path.join(dir, "build/score.json")));
  const model = JSON.parse(fs.readFileSync(path.join(dir, "build/model.json")));
  return {
    id: sample.id,
    label: pack.name,
    model,
    score: score.overall.score,
    silhouetteIoU: score.overall.silhouetteIoU,
    volumeIoU: score.geometry.volumeIoU,
    source: pack.license.source,
    images: pack.images.map((p) => ({
      src: `${dir}/${p.file}`,
      alt: `${pack.name}, ${p.view} reference view`,
    })),
  };
});
const source = `// Generated by tools/refpack-toy.mjs from the measured good builds.\n// Made by Ryan with Codex (GPT-6). Code MIT; original fitted shapes CC0.\nexport const REFERENCE_BUILDS = ${JSON.stringify(builds, null, 2)};\n`;
fs.writeFileSync("src/refbuild/data.js", await prettier.format(source, { parser: "babel" }));
const gallery = builds.map((b) => ({
  label: b.label,
  caption: `${b.score.toFixed(1)}/100 · silhouette ${(b.silhouetteIoU * 100).toFixed(1)}% · volume ${(b.volumeIoU * 100).toFixed(1)}%`,
  images: b.images,
}));
fs.writeFileSync(
  "src/refbuild/gallery-data.js",
  await prettier.format(
    `// Generated reference captions and paths; geometry loads only with the toy.\nexport const REFERENCE_GALLERY = ${JSON.stringify(gallery, null, 2)};\n`,
    { parser: "babel" },
  ),
);
console.log("src/refbuild/data.js: five CC0, measured good builds");
const thumbnail = "assets/toys/built-from-pictures/thumb.webp";
const assetRecords = {
  schema: 1,
  author: "Made by Ryan with Codex (GPT-6)",
  codeLicense: "MIT",
  geometryLicense: "CC0-1.0",
  checked: "2026-10-17",
  source: "tools/refpack-samples/",
  changes:
    "Fitted kit recipes from six reference renders per CC0 model; no source geometry read by the builder.",
  ...(fs.existsSync(thumbnail)
    ? {
        thumbnail: {
          file: thumbnail,
          license: "CC0-1.0",
          source: "tools/refpack-samples/reference-duck/build/model.json",
          sha256: crypto.createHash("sha256").update(fs.readFileSync(thumbnail)).digest("hex"),
          changes: "Shelf thumbnail rendered from the fitted kit recipe.",
        },
      }
    : {}),
};
fs.writeFileSync(
  "src/refbuild/asset-records.json",
  await prettier.format(JSON.stringify(assetRecords), { parser: "json" }),
);
