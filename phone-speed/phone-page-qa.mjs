import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
await import('./llvmpipe-probe.mjs');
const out='.cache/phone-speed/phone-page-qa';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.SPLASHERY_CHROMIUM,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--enable-webgl']});
const errors=[], uploads=[];
const pageModules=Object.fromEntries(await Promise.all(['phone-speed.html','phone-speed-page.js','phone-speed-metrics.js','phone-speed-hybrid.js','phone-speed-slowest.json'].map(async name=>[name,createHash('sha256').update(await fs.readFile('tools/pages/'+name)).digest('hex')])));
const evidence={pageModules,toolingRevision:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),source:process.env.PHONE_SPEED_SOURCE||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),started:new Date().toISOString(),browser:browser.version(),checks:{}};
try{
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:3,isMobile:true,hasTouch:true,colorScheme:'light',acceptDownloads:true});
 await context.grantPermissions(['clipboard-read','clipboard-write']);
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))uploads.push({url:r.url(),method:r.method()});});
 page.on('console',m=>{if(m.text().startsWith('PHONE_QA '))console.log(m.text());});
 await page.goto('http://127.0.0.1:4173/tools/pages/phone-speed.html');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'tests/screenshots/cdx-speed-phone-page-390x844.png',scale:'css'});
 await page.evaluate(()=>new MutationObserver(()=>console.log('PHONE_QA '+document.querySelector('[role=status]').textContent)).observe(document.querySelector('[role=status]'),{childList:true,subtree:true}));
 await page.getByRole('button',{name:'Start run',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[role=status]').textContent.startsWith('Complete.'),null,{timeout:1800000});
 const json=await page.locator('#json').inputValue();
 await fs.writeFile(`${out}/full30.json`,json);
 const result=JSON.parse(json), expected=(await(await fetch('http://127.0.0.1:4173/tools/pages/phone-speed-slowest.json')).json()).ids;
 assert.deepEqual(result.rows.map(r=>r.id),expected);
 assert.equal(new Set(result.rows.map(r=>r.id)).size,30);
 for(const r of result.rows){assert.equal(r.error,undefined);assert.deepEqual(r.errors,[]);assert.ok(r.firstViewMs>0&&r.idle.count>=8&&r.tap.count>=8);assert.equal(r.profile,'low');assert.deepEqual(r.viewport,[390,844]);}
 evidence.checks.complete30=true;
 const table=await page.locator('#results').inputValue();
 await fs.writeFile(`${out}/table.tsv`,table);
 await page.getByRole('button',{name:'Copy table',exact:true}).click();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),table);
 evidence.checks.clipboard=true;
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Save JSON',exact:true}).click();
 const download=await pending;await download.saveAs(`${out}/download.json`);
 assert.deepEqual(JSON.parse(await fs.readFile(`${out}/download.json`,'utf8')),result);
 evidence.checks.download=true;
 await page.screenshot({path:'tests/screenshots/cdx-speed-phone-page-results-390x844.png',scale:'css'});
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:undefined}));
 await page.getByRole('button',{name:'Copy table',exact:true}).click();
 assert.match(await page.getByRole('status').textContent(),/Select and copy/);
 assert.equal(await page.locator('#results').evaluate(el=>el.selectionEnd-el.selectionStart),table.length);
 evidence.checks.clipboardFallback=true;
 await page.goto('http://127.0.0.1:4173/tools/pages/phone-speed.html?ids=tennis-ball,cactus&duration=250');
 await page.getByRole('button',{name:'Start run',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===1,null,{timeout:120000});
 await page.getByRole('button',{name:'Stop',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[role=status]').textContent.startsWith('Stopped.'));
 assert.equal(JSON.parse(await page.locator('#json').inputValue()).rows.length,1);
 assert.equal(await page.locator('iframe').count(),0);
 evidence.checks.stopRetainsCompleted=true;
 await context.close();
 const desktop=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1,colorScheme:'light'});
 const wide=await desktop.newPage();wide.on('pageerror',e=>errors.push(e.message));
 await wide.goto('http://127.0.0.1:4173/tools/pages/phone-speed.html?ids=tennis-ball&duration=250');
 await wide.screenshot({path:'tests/screenshots/cdx-speed-phone-page-1440x900.png'});
 await wide.getByRole('button',{name:'Start run',exact:true}).click();
 await wide.waitForFunction(()=>document.querySelector('[role=status]').textContent.startsWith('Complete.'),null,{timeout:120000});
 assert.equal(await wide.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await wide.screenshot({path:'tests/screenshots/cdx-speed-phone-page-results-1440x900.png'});
 evidence.checks.desktop=true;
 await desktop.close();
 assert.deepEqual(errors,[]);assert.deepEqual(uploads,[]);
 for(const name of ['cdx-speed-phone-page-390x844.png','cdx-speed-phone-page-results-390x844.png','cdx-speed-phone-page-1440x900.png','cdx-speed-phone-page-results-1440x900.png'])await fs.copyFile(`tests/screenshots/${name}`,`${out}/${name}`);
 evidence.errors=errors;evidence.uploads=uploads;evidence.completed=new Date().toISOString();
 await fs.writeFile(`${out}/checks.json`,JSON.stringify(evidence,null,2));
 console.log(JSON.stringify(evidence));
}finally{await browser.close();}
